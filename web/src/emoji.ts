/**
 * Каталог эмодзи для пикера и разбор ключа реакции.
 *
 * Каталог захардкожен, а не тянется из библиотеки вроде emoji-mart: тем нужен
 * либо свой спрайт-лист картинками (сотни килобайт на каждую загрузку
 * страницы), либо тот же unicode, что и здесь, но с полным индексом на ~1800
 * символов. Для чата на компанию друзей достаточно выборки живых эмодзи —
 * зато без единой новой зависимости и без сетевого запроса за данными.
 *
 * Ключевые слова русские: пикер ищет по ним (см. searchEmoji), а пользователи
 * тут пишут по-русски.
 */

export interface EmojiCategory {
  id: string
  /** Подпись вкладки в пикере. */
  label: string
  /** Символ вкладки — он же первый эмодзи категории. */
  icon: string
  emoji: EmojiEntry[]
}

export interface EmojiEntry {
  /** Сам символ — он же ключ реакции (см. parseEmojiKey). */
  char: string
  /** По этим словам эмодзи находится поиском. */
  keywords: string[]
}

const e = (char: string, ...keywords: string[]): EmojiEntry => ({ char, keywords })

