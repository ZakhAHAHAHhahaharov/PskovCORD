"""Вычистка чувствительного из текста ошибки ПЕРЕД сохранением.

Отчёты об ошибках — это тот редкий поток, который несёт в админку сырой
текст с клиента, и в нём легко приезжает лишнее: JWT из заголовка запроса,
попавший в сообщение сетевой ошибки; токен одноразового входа в query-строке
роута; содержимое сообщения пользователя внутри «Cannot read ... of <текст>».

Чистим на входе, а не при показе: в базе не должно лежать того, что мы не
готовы показать любому, у кого есть доступ в админку.
"""
import re

# JWT — три base64url-сегмента через точку. Именно им ходит авторизация
# (SIMPLE_JWT), поэтому он тут первым.
_JWT = re.compile(r"\beyJ[\w-]{6,}\.[\w-]{6,}\.[\w-]{6,}\b")
# Длинные «словарно-невозможные» строки — одноразовые коды, ключи сессий,
# refresh-токены. Порог 24 подобран так, чтобы не задевать обычные слова и
# имена классов/функций из стектрейса.
_SECRETish = re.compile(r"\b[A-Za-z0-9_-]{24,}\b")
_EMAIL = re.compile(r"\b[\w.+-]+@[\w-]+\.[\w.]+\b")
# Значение любого параметра, чьё имя намекает на секрет.
_SENSITIVE_PARAM = re.compile(
    r"\b(token|access|refresh|password|passwd|secret|key|code|auth|session)"
    r"\s*[=:]\s*[^\s&,;)\"']+",
    re.I,
)

_KEEP_PREFIXES = ("data:image/",)


def scrub(text: str, limit: int = 8000) -> str:
    """Текст без секретов и почт, обрезанный до limit.

    Порядок важен: сперва именованные параметры (там значение может быть
    коротким и под _SECRETish не попасть), потом JWT, потом всё остальное."""
    if not text:
        return ""
    # data-URL картинки режем целиком: аватары в этом проекте ездят именно
    # так, и один такой в стектрейсе — это мегабайты мусора в базе.
    for prefix in _KEEP_PREFIXES:
        text = re.sub(re.escape(prefix) + r"[^\s\"')]+", prefix + "<вырезано>", text)
    text = _SENSITIVE_PARAM.sub(lambda m: f"{m.group(1)}=<вырезано>", text)
    text = _JWT.sub("<jwt>", text)
    text = _EMAIL.sub("<email>", text)
    text = _SECRETish.sub("<вырезано>", text)
    return text[:limit]


def scrub_route(route: str, limit: int = 500) -> str:
    """Роут без query-строки целиком. Не выборочно по параметрам: в SPA в
    query приезжают и коды приглашений, и токены QR-входа, и проще потерять
    весь хвост, чем гадать, какой параметр безопасен."""
    if not route:
        return ""
    return scrub(route.split("?")[0].split("#")[0], limit)
